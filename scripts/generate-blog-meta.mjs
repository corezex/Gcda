#!/usr/bin/env node
// Generates data/blogMeta.js — a lean slug/title/description/category index.
//
// Why: app/blog/[slug]/opengraph-image.js runs on the Edge runtime. Importing
// data/blog.js (3.1 MB of full article bodies) pulled the whole array into the
// edge bundle, producing a 3.4 MB function that exceeds Vercel's Edge Function
// size limit (1 MB Hobby / 2 MB Pro compressed) and fails deployment.
// The OG image only needs title/description/category, so we ship those alone.
//
// Run automatically via `npm run prebuild`.

import fs from 'fs';
import path from 'path';
import { pathToFileURL } from 'url';

const root = process.cwd();
const src = pathToFileURL(path.join(root, 'data/blog.js')).href;
const { blogPosts } = await import(src);

const meta = blogPosts.map((p) => ({
  slug: p.slug,
  title: p.title,
  description: p.description,
  category: p.category,
}));

const out = `// AUTO-GENERATED by scripts/generate-blog-meta.mjs — do not edit by hand.
// Lean blog index (slug/title/description/category) for size-constrained
// runtimes such as the Edge OG image route. Regenerate with \`npm run prebuild\`.

export const blogMeta = ${JSON.stringify(meta, null, 2)};

export function getBlogMetaBySlug(slug) {
  return blogMeta.find((post) => post.slug === slug);
}
`;

fs.writeFileSync(path.join(root, 'data/blogMeta.js'), out, 'utf8');
console.log(
  `Wrote data/blogMeta.js — ${meta.length} posts, ${(out.length / 1024).toFixed(0)} KB (source blog.js is ${(fs.statSync(path.join(root, 'data/blog.js')).size / 1024).toFixed(0)} KB)`
);
